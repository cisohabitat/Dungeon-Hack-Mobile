'use strict';
const { test } = require('@playwright/test');
const { errs, shot, note, logTail, clearBoons, arena, place } = require('./pt2-util');
const T = 'd';

test('Daily Delve, Hall of Heroes, relic codex', async ({ page }) => {
  const E = errs(page, T);
  await page.goto('/');
  await page.click('#btn-daily');
  await page.waitForTimeout(400);
  await shot(page, 'd01-daily-prologue');
  note(T, { rules: await page.textContent('#pro-rules'), who: await page.textContent('#pro-who') });
  await page.click('#pro-begin');
  await page.waitForFunction(() => typeof Game !== 'undefined' && !!Game.state());
  await page.waitForTimeout(800);
  await shot(page, 'd02-daily-start');
  note(T, await page.evaluate(() => ({ cls: Game.player().cls, bg: Game.player().bg, name: Game.player().name, opts: Game.state().opts })));
  // menu shows daily
  await page.tap('[data-open="menu"]'); await page.waitForTimeout(200); await shot(page, 'd03-daily-menu');
  note(T, { menuSeed: await page.textContent('#m-seed'), saveDisabled: await page.locator('#m-save').isDisabled(), loadDisabled: await page.locator('#m-load').isDisabled() });
  await page.tap('#m-quit'); await page.waitForTimeout(400);
  await shot(page, 'd04-title-daily-waiting');
  note(T, { daily: await page.textContent('#daily-summary') });
  await page.click('#btn-daily'); await page.waitForTimeout(600);
  await clearBoons(page);
  // die
  await page.evaluate(() => { const p = Game.player(); p.hp = 1; });
  await arena(page);
  await place(page, 'orc', 1, { hp: 99, nextAct: 0 });
  await page.waitForSelector('#screen-end.active', { timeout: 20000 });
  await page.waitForTimeout(800);
  await shot(page, 'd05-daily-end');
  await page.click('#end-share').catch(e => note(T, 'share click ' + e.message.slice(0, 80)));
  await page.waitForTimeout(400);
  await page.locator('#end-share-line').scrollIntoViewIfNeeded().catch(() => {});
  await shot(page, 'd06-daily-share');
  note(T, { share: await page.textContent('#end-share-line'), btn: await page.textContent('#end-share') });
  await page.click('#end-title-btn');
  await page.waitForTimeout(400);
  await shot(page, 'd07-title-after-daily');
  note(T, { daily: await page.textContent('#daily-summary') });
  await page.click('#btn-daily'); await page.waitForTimeout(600);
  await shot(page, 'd08-daily-second-try');
  note(T, { secondTryScreen: await page.evaluate(() => document.querySelector('.screen.active').id) });
  await page.click('#btn-hall'); await page.waitForTimeout(400);
  await shot(page, 'd09-hall');
  await page.locator('#hall-list').scrollIntoViewIfNeeded(); await shot(page, 'd10-hall-list');
  await page.click('#hall-relics'); await page.waitForTimeout(300);
  await shot(page, 'd11-codex');
  await page.click('#relics-back'); await page.click('#hall-back');
  await page.click('#btn-beasts'); await page.waitForTimeout(300); await shot(page, 'd12-title-bestiary');
  await page.click('#beasts-back');
  await page.click('#btn-help'); await page.waitForTimeout(300); await shot(page, 'd13-help');
  E.dump();
});
